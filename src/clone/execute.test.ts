    expect(events[1]?.label).toBe(NASTY);
    expect(events[0]).toMatchObject({ at_ms: '2024-03-01T08:00:00.124Z', iso: '2026-01-01T00:00:00Z', flag: true, big: '9007199254740993', dbig: '18014398509481986', raw: '00ff5c09', note: null });
    expect(events[1]?.note).toBe('');
    expect(events.map((e) => e.flag)).toEqual([true, false, true]);
    expect(events[0]?.doc).toEqual({ a: [1.0], b: 1 });
    expect(await q('select country, name, age::text from people order by country collate "C", name collate "C"')).toHaveLength(10);
    expect(await q<{ id: string }>('select id::text from tokens order by id')).toEqual([{ id: '00000000-0000-4000-8000-000000000003' }, { id: 'aaaaaaaa-0000-4000-8000-000000000002' }, { id: 'ffffffff-0000-4000-8000-000000000001' }]);
