    expect(fks[0]?.def).toContain('ON DELETE CASCADE');
    expect(fks[1]?.def).toContain('DEFERRABLE INITIALLY DEFERRED');

    const [receipt] = await q<{ run_id: string; per_table: Record<string, { rows: number; sha256: string }> }>('select run_id::text, per_table from db_kit.clone_receipt');
    expect(receipt?.run_id).toBe(result.runId);
    expect(receipt?.per_table.events).toEqual({ rows: 3, sha256: result.tables.find((t) => t.table === 'events')?.sha256 });
